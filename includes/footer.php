/* Page-to-page navigation: a thin accent bar only, and only when the next
   page takes longer than 200ms. The full overlay is never used for links. */
(function () {
  var bar = document.getElementById('hlBar');
  if (!bar || !window.PageLoader) return;
  var fill = bar.firstElementChild;
  var key = 'hl-nav-at';
  var timer = null;
  var fadeTimer = null;
  var resetTimer = null;

  function barStart() {
    if (timer) { clearTimeout(timer); timer = null; }
    clearTimeout(fadeTimer);
    clearTimeout(resetTimer);
    bar.classList.add('is-active');
    fill.style.transition = 'none';
    fill.style.width = '0';
    void fill.offsetWidth;
    fill.style.transition = '';
    fill.style.width = '60%';
  }

  function barDone() {
    clearTimeout(fadeTimer);
    clearTimeout(resetTimer);
    fill.style.width = '100%';
    fadeTimer = window.setTimeout(function () {
      bar.classList.remove('is-active');
      resetTimer = window.setTimeout(function () {
        fill.style.transition = 'none';
        fill.style.width = '0';
        void fill.offsetWidth;
        fill.style.transition = '';
      }, 300);
    }, 300);
  }

  window.PageLoader.barStart = barStart;
  window.PageLoader.barDone = barDone;

  // Pick up a bar that was already showing while the previous page unloaded.
  var navAt = 0;
  try {
    navAt = parseInt(sessionStorage.getItem(key), 10) || 0;
    sessionStorage.removeItem(key);
  } catch (e) {}
  if (navAt && Date.now() - navAt >= 200) {
    bar.classList.add('is-active');
    fill.style.transition = 'none';
    fill.style.width = '60%';
    void fill.offsetWidth;
    fill.style.transition = '';
    window.setTimeout(barDone, 0);
  }

  document.addEventListener('click', function (event) {
    if (event.defaultPrevented) return;
    if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    var link = event.target && event.target.closest ? event.target.closest('a') : null;
    if (!link || link.target === '_blank' || link.hasAttribute('download')) return;
    var href = link.getAttribute('href');
    if (!href || href.charAt(0) === '#' || /^(mailto:|tel:|javascript:)/i.test(href)) return;
    var destination;
    try { destination = new URL(link.href, window.location.href); } catch (err) { return; }
    if (destination.origin !== window.location.origin) return;
    if (destination.pathname === window.location.pathname && destination.search === window.location.search) return;
    try { sessionStorage.setItem(key, String(Date.now())); } catch (e) {}
    timer = window.setTimeout(function () {
      barStart();
      // If that navigation was cancelled, finish the bar instead of leaving it.
      window.setTimeout(function () {
        barDone();
        try { sessionStorage.removeItem(key); } catch (e) {}
      }, 10000);
    }, 200);
  }, false);
})();
</script>
